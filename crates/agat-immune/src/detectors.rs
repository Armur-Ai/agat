//! Detectors and the detector repertoire.
//!
//! A detector is the computational analogue of a mature lymphocyte: a
//! point in antigen signature space with a recognition radius. It
//! *recognizes* (binds) any antigen whose signature falls within that
//! radius. Because every detector is generated to sit in **non-self**
//! space (see [`crate::negative_selection`]), a binding means
//! "different from benign self" — and, once a detector has been matured
//! by clonal selection onto a known family, it also carries that
//! family's label.
//!
//! The geometry here is the real-valued V-detector form (Ji &
//! Dasgupta, 2004): variable-radius hyperspheres under the Euclidean
//! metric from `agat-antigen`.

use agat_antigen::euclidean_distance;
use serde::{Deserialize, Serialize};

/// Where a detector came from. Tracked so the repertoire can report how
/// much of its recognition power is innate (negative selection) versus
/// learned (clonal selection / memory).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum DetectorOrigin {
    /// Generated by negative selection knowing only self.
    NegativeSelection,
    /// Produced by clonal selection / hypermutation of a parent detector.
    Clone,
    /// Promoted to a long-lived memory cell.
    Memory,
}

/// A single detector: a hypersphere in signature space.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Detector {
    /// Center of the recognition region.
    pub center: Vec<f64>,
    /// Recognition radius. An antigen binds iff its signature is within
    /// this Euclidean distance of `center`.
    pub radius: f64,
    /// 0 for naive (negative-selection) detectors; incremented each time
    /// a detector is matured by clonal selection.
    pub generation: u32,
    /// Family label, assigned once a detector is matured onto a known
    /// family. `None` for naive anomaly detectors.
    pub family: Option<String>,
    pub origin: DetectorOrigin,
    /// Rounds survived without being usefully selected — used to retire
    /// weak/old detectors during clonal selection.
    pub age: u32,
}

impl Detector {
    pub fn new(center: Vec<f64>, radius: f64, origin: DetectorOrigin) -> Self {
        Self {
            center,
            radius,
            generation: 0,
            family: None,
            origin,
            age: 0,
        }
    }

    /// Distance from this detector's center to a signature.
    pub fn distance(&self, sig: &[f64]) -> f64 {
        euclidean_distance(&self.center, sig)
    }

    /// Stable content id (family + quantized center + radius). A detector's
    /// geometry is its identity, so two identical detectors dedupe on merge
    /// (R1 · herd immunity).
    pub fn detector_id(&self) -> String {
        crate::ident::hash_id(
            self.family.as_deref().unwrap_or(""),
            &self.center,
            &[self.radius],
        )
    }

    /// Whether the antigen binds this detector (lies within the radius).
    pub fn matches(&self, sig: &[f64]) -> bool {
        self.distance(sig) <= self.radius
    }

    /// Binding affinity in `(-∞, 1]`: 1.0 at the center, 0.0 on the
    /// surface, negative outside. Used to rank competing detectors and
    /// to drive clonal selection (clone ∝ affinity, mutate ∝ 1/affinity).
    pub fn affinity(&self, sig: &[f64]) -> f64 {
        if self.radius <= 0.0 {
            return if self.distance(sig) == 0.0 {
                1.0
            } else {
                f64::NEG_INFINITY
            };
        }
        1.0 - self.distance(sig) / self.radius
    }
}

/// A collection of detectors covering (some of) non-self space.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Repertoire {
    pub dim: usize,
    pub detectors: Vec<Detector>,
}

impl Repertoire {
    pub fn new(dim: usize) -> Self {
        Self {
            dim,
            detectors: Vec::new(),
        }
    }

    pub fn len(&self) -> usize {
        self.detectors.len()
    }

    pub fn is_empty(&self) -> bool {
        self.detectors.is_empty()
    }

    /// Whether *any* detector binds this signature (i.e. it is non-self
    /// as far as the repertoire is concerned).
    pub fn covers(&self, sig: &[f64]) -> bool {
        self.detectors.iter().any(|d| d.matches(sig))
    }

    /// How many naive vs matured detectors the repertoire holds.
    pub fn composition(&self) -> (usize, usize) {
        let matured = self.detectors.iter().filter(|d| d.family.is_some()).count();
        (self.detectors.len() - matured, matured)
    }

    /// Merge another repertoire into this one (R1 · herd immunity). Detectors
    /// are deduped by `detector_id` (keeping the wider radius on an exact
    /// collision) and sorted, so the merge is commutative and idempotent.
    pub fn union(&mut self, other: &Repertoire) {
        if self.dim == 0 {
            self.dim = other.dim;
        }
        for d in &other.detectors {
            let id = d.detector_id();
            match self.detectors.iter_mut().find(|x| x.detector_id() == id) {
                Some(existing) if d.radius > existing.radius => *existing = d.clone(),
                Some(_) => {}
                None => self.detectors.push(d.clone()),
            }
        }
        self.detectors.sort_by_cached_key(|d| d.detector_id());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matching_and_affinity() {
        let d = Detector::new(vec![0.0, 0.0], 1.0, DetectorOrigin::NegativeSelection);
        assert!(d.matches(&[0.5, 0.0]));
        assert!(!d.matches(&[2.0, 0.0]));
        assert!((d.affinity(&[0.0, 0.0]) - 1.0).abs() < 1e-9); // center
        assert!(d.affinity(&[1.0, 0.0]).abs() < 1e-9); // surface
        assert!(d.affinity(&[2.0, 0.0]) < 0.0); // outside
    }

    #[test]
    fn repertoire_coverage() {
        let mut r = Repertoire::new(2);
        r.detectors.push(Detector::new(
            vec![1.0, 1.0],
            0.5,
            DetectorOrigin::NegativeSelection,
        ));
        assert!(r.covers(&[1.1, 1.0]));
        assert!(!r.covers(&[0.0, 0.0]));
    }

    #[test]
    fn union_dedupes_and_is_idempotent() {
        let d1 = Detector::new(vec![0.1, 0.2], 0.3, DetectorOrigin::NegativeSelection);
        let d2 = Detector::new(vec![0.8, 0.9], 0.3, DetectorOrigin::NegativeSelection);
        let mut a = Repertoire::new(2);
        a.detectors.push(d1.clone());
        let mut b = Repertoire::new(2);
        b.detectors.push(d1.clone()); // duplicate of d1
        b.detectors.push(d2.clone());

        a.union(&b);
        assert_eq!(a.len(), 2, "the duplicate must collapse");
        let before: Vec<_> = a.detectors.iter().map(|d| d.detector_id()).collect();
        a.union(&b);
        let after: Vec<_> = a.detectors.iter().map(|d| d.detector_id()).collect();
        assert_eq!(before, after, "union must be idempotent");
    }
}
